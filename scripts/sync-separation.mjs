// Copy the app's separation code and recipe into this package: the app is the one source, these are generated mirrors.
//
//   node scripts/sync-separation.mjs           write the mirrors
//   node scripts/sync-separation.mjs --check   exit 1 if any mirror differs from what the app would produce
//
// The app (C:\Coding Projects\aurora\aurora, or AURORA_REPO) owns the routes, the exact-key output resolver,
// the audio content checks, the generated MVSEP catalog, the checked route runner and the extract catalog.
// This package is Node16 ESM, so relative imports gain `.js`; the provider interfaces run-route.ts needs are
// lifted from the app's src/shared/types/index.ts into a generated contracts.ts. Never edit a mirror: edit the
// app's file and rerun.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const MCP = resolve(HERE, '..')
const APP = resolve(process.env.AURORA_REPO ?? join(MCP, '..', 'aurora'))
const OUT = join(MCP, 'packages', 'shared', 'src')

// app path → mirror path (relative to packages/shared/src)
const FILES = {
  'src/shared/separation/routes.ts': 'separation/routes.ts',
  'src/shared/separation/identify.ts': 'separation/identify.ts',
  'src/shared/separation/content-check.ts': 'separation/content-check.ts',
  'src/shared/separation/mvsep-catalog.generated.ts': 'separation/mvsep-catalog.generated.ts',
  'src/main/split/run-route.ts': 'separation/run-route.ts',
  'src/shared/extract-catalog.ts': 'extract-catalog.ts',
  'src/shared/recipe.ts': 'recipe.ts'
}
const CONTRACT_TYPES = ['MvsepJobSpec', 'SeparationResultFile', 'SeparationResult', 'SeparationProvider']

const banner = (src) =>
  `// GENERATED by aurora-mcp/scripts/sync-separation.mjs from aurora/${src}. Do not edit: edit the app's file\n` +
  `// and run \`node scripts/sync-separation.mjs\`. \`--check\` (in npm run typecheck) fails on drift.\n`

/** Rewrite one app file's imports for its place in this package. */
function adapt(code, src) {
  return code.replace(/(from\s+')([^']+)(')/g, (m, a, spec, z) => {
    if (!spec.startsWith('.')) return m
    let target = spec
    if (src === 'src/main/split/run-route.ts') {
      if (spec.startsWith('../../shared/separation/')) target = './' + spec.slice('../../shared/separation/'.length)
      else if (spec === '../../shared/types') target = './contracts'
      // '../audio/wav' resolves to packages/shared/src/audio/wav (the codec port), same relative path.
    }
    return a + (target.endsWith('.js') ? target : target + '.js') + z
  })
}

/** The provider interfaces, cut verbatim from the app's types. */
function contracts() {
  const types = readFileSync(join(APP, 'src/shared/types/index.ts'), 'utf8')
  const blocks = CONTRACT_TYPES.map((name) => {
    const decl = types.search(new RegExp(`export interface ${name}\\b`))
    if (decl < 0) throw new Error(`app types lack interface ${name}`)
    // Keep a doc comment only when it sits directly above the declaration.
    const before = types.slice(0, decl)
    const doc = before.match(/\/\*\*(?:(?!\*\/)[^])*\*\/\s*$/)
    const start = doc ? decl - doc[0].length : decl
    let i = types.indexOf('{', start)
    let depth = 0
    for (; i < types.length; i++) {
      if (types[i] === '{') depth++
      else if (types[i] === '}' && --depth === 0) break
    }
    return types.slice(start, i + 1).trim()
  })
  return banner('src/shared/types/index.ts (the separation provider interfaces)') + '\n' + blocks.join('\n\n') + '\n'
}

const outputs = { 'separation/contracts.ts': contracts() }
for (const [src, dest] of Object.entries(FILES)) {
  const path = join(APP, src)
  if (!existsSync(path)) throw new Error(`app file missing: ${path} (set AURORA_REPO)`)
  outputs[dest] = banner(src) + adapt(readFileSync(path, 'utf8'), src)
}

const check = process.argv.includes('--check')
const drift = []
for (const [dest, body] of Object.entries(outputs)) {
  const path = join(OUT, dest)
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null
  if (current === body) continue
  drift.push(dest)
  if (!check) {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, body)
  }
}
if (check) {
  if (drift.length) {
    console.error(`separation mirrors are out of date with the app: ${drift.join(', ')}. Run node scripts/sync-separation.mjs`)
    process.exit(1)
  }
  console.log(`separation mirrors match the app (${Object.keys(outputs).length} files)`)
} else {
  console.log(`synced ${drift.length} of ${Object.keys(outputs).length} files from ${APP}`)
}
